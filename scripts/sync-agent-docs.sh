#!/usr/bin/env bash
# Generate GEMINI.md from CLAUDE.md.
#
# CLAUDE.md is the source-of-truth for both agents. This script copies it to
# GEMINI.md, swapping the title/header so Gemini CLI reads it as its own
# instruction file. Edit CLAUDE.md, run this script, commit both.
#
# Usage:
#   ./scripts/sync-agent-docs.sh

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SRC="$REPO_ROOT/CLAUDE.md"
DST="$REPO_ROOT/GEMINI.md"

if [[ ! -f "$SRC" ]]; then
  echo "error: $SRC not found" >&2
  exit 1
fi

HEADER='<!--
  Auto-generated from CLAUDE.md by scripts/sync-agent-docs.sh.
  DO NOT EDIT this file directly. Edit CLAUDE.md and re-run the script.
-->

'

# Swap the H1 and the subtitle line so Gemini reads it as its own instruction
# file. Everything else is shared verbatim.
{
  printf '%s' "$HEADER"
  awk '
    NR==1 && /^# Lumen Goods — Claude Code Project Instructions/ {
      print "# Lumen Goods — Gemini CLI Project Instructions"; next
    }
    /^> Persistent guidance for Claude Code/ {
      print "> Persistent guidance for Gemini CLI working in this repository. Read top-to-bottom before any task."; next
    }
    { print }
  ' "$SRC"
} > "$DST"

echo "wrote $DST"
